/**
 * Splits a crop name into English and Marathi parts.
 * Example: "Onion (कांदा)" -> { english: "Onion", marathi: "कांदा" }
 * Example: "Onion" -> { english: "Onion", marathi: "कांदा" }
 */
export function splitCropName(rawName) {
  if (!rawName) return { english: '', marathi: '' };
  const str = String(rawName).trim();

  // If already in "English (मराठी)" format
  const parenMatch = str.match(/^(.+?)\s*\(([\u0900-\u097F\s/]+)\)$/);
  if (parenMatch) {
    return {
      english: parenMatch[1].trim(),
      marathi: parenMatch[2].trim()
    };
  }

  // Look up in dictionary by lowercased key
  const key = str.toLowerCase();
  const entry = CROP_MARATHI_MAP[key];
  if (entry) {
    return {
      english: entry.en,
      marathi: entry.mr
    };
  }

  // Check if string contains Devanagari script directly
  const hasDevanagari = /[\u0900-\u097F]/.test(str);
  if (hasDevanagari) {
    return { english: str, marathi: str };
  }

  return { english: str, marathi: '' };
}

/**
 * Formats a crop name into a bilingual "English (मराठी)" string.
 * Example: "Onion" -> "Onion (कांदा)"
 * Example: "Onion (कांदा)" -> "Onion (कांदा)"
 */
export function formatCropDisplayName(rawName) {
  if (!rawName) return '';
  const { english, marathi } = splitCropName(rawName);
  if (marathi && english && !english.includes(marathi)) {
    return `${english} (${marathi})`;
  }
  return english || String(rawName);
}

